#!/usr/bin/env node
/**
 * Stamp the standalone landing page with release and benchmark data.
 *
 * - `landing/release.js` comes from the release tag (or the latest local tag).
 * - `landing/benchmarks.js` comes from the results table in docs/BENCHMARKS.md.
 *
 * Run `node scripts/sync-landing.mjs` to write both files. `--check` verifies
 * that the committed files are current without writing anything, which is what
 * CI and the release workflow use.
 *
 *   node scripts/sync-landing.mjs --tag v0.2.0-rc.2
 *   node scripts/sync-landing.mjs --check
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");

function argument(name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : null;
}

const TAG_PATTERN = /^v\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/;
const packagePath = path.join(root, "package.json");
const benchmarksDocPath = path.join(root, "docs", "BENCHMARKS.md");
const benchmarksPath = path.join(root, "landing", "benchmarks.js");
const releasePath = path.join(root, "landing", "release.js");

function fail(message) {
  console.error(`LANDING_SYNC_FAILED: ${message}`);
  process.exit(1);
}

function readPackage() {
  try {
    return JSON.parse(readFileSync(packagePath, "utf8"));
  } catch (error) {
    fail(`cannot read package.json (${error.message})`);
  }
}

function repositorySlug(pkg) {
  const explicit = argument("--repo");
  if (explicit) return explicit;
  const url = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url ?? "";
  const match = url.match(/github\.com[/:]([^/]+)\/([^/]+?)(?:\.git)?\/?$/);
  if (!match) fail(`cannot derive a GitHub repository from "${url}"`);
  return `${match[1]}/${match[2]}`;
}

/**
 * The tag is the release source of truth. CI passes it explicitly; locally we
 * use the nearest reachable tag, then whatever the committed page already uses
 * so a shallow checkout without tags can still validate its benchmarks.
 */
function resolveTag() {
  const explicit = argument("--tag");
  if (explicit) {
    if (!TAG_PATTERN.test(explicit)) fail(`"${explicit}" is not a release tag such as v0.2.0 or v0.2.0-rc.2`);
    return explicit;
  }

  const envTag = process.env.GITHUB_REF_NAME;
  if (envTag && TAG_PATTERN.test(envTag)) return envTag;

  const described = spawnSync(
    "git",
    ["describe", "--tags", "--abbrev=0", "--match", "v[0-9]*"],
    { cwd: root, encoding: "utf8" },
  );
  if (described.status === 0) {
    const tag = described.stdout.trim();
    if (TAG_PATTERN.test(tag)) return tag;
  }

  const committed = existsSync(releasePath)
    ? readFileSync(releasePath, "utf8").match(/"tag":\s*"([^"]+)"/)?.[1]
    : null;
  if (committed && TAG_PATTERN.test(committed)) return committed;

  return `v${readPackage().version}`;
}

function parseBenchmarks() {
  let text;
  try {
    text = readFileSync(benchmarksDocPath, "utf8");
  } catch (error) {
    fail(`cannot read docs/BENCHMARKS.md (${error.message})`);
  }

  const measuredAt = text.match(/Generated by .*? on (\d{4}-\d{2}-\d{2})/)?.[1] ?? null;
  const rows = [];

  for (const line of text.split(/\r?\n/)) {
    if (!line.startsWith("| `")) continue;
    const cells = line.split("|").slice(1, -1).map((cell) => cell.trim());
    if (cells.length < 8) continue;

    const full = cells[0].replace(/^`|`$/g, "");
    const method = cells[1];
    const runs = Number(cells[2]);
    const median = Number.parseFloat(cells[3]);
    const files = Number(cells[6].replace(/,/g, ""));

    if (!full || !method || !Number.isFinite(runs) || !Number.isFinite(median) || !Number.isFinite(files)) {
      continue;
    }

    rows.push({
      // A measured 0.00 s would produce a zero-length bar; keep a floor so the
      // row is still visible while the page formats it as 0.00 s.
      label: full.split("\\").pop() || full,
      full,
      median: median === 0 ? 0.001 : median,
      files,
      size: cells[7],
      peak: cells[5],
      runs,
      method,
    });
  }

  if (!rows.length) {
    fail("docs/BENCHMARKS.md has no parsable result rows");
  }

  return {
    measuredAt,
    // All rows are produced by the same benchmark command; use the first row
    // for the shared method/runs label and keep per-row runs out of the page.
    runs: rows[0].runs,
    method: rows[0].method,
    rows: rows.map(({ runs: _runs, method: _method, ...row }) => row),
  };
}

function renderBenchmarks(benchmarks) {
  const source = {
    file: "docs/BENCHMARKS.md",
    measuredAt: benchmarks.measuredAt,
    runs: benchmarks.runs,
    method: benchmarks.method,
    methodLabel:
      benchmarks.method === "directory"
        ? "directory walk"
        : benchmarks.method === "mft"
          ? "MFT"
          : benchmarks.method,
  };
  return `// Generated by scripts/sync-landing.mjs from docs/BENCHMARKS.md.
// Do not edit by hand: run \`npm run landing:sync\`.
export const BENCHMARK_SOURCE = ${JSON.stringify(source, null, 2)};

export const BENCHMARKS = ${JSON.stringify(benchmarks.rows, null, 2)};
`;
}

function renderRelease(tag, repo) {
  const version = tag.replace(/^v/, "");
  const prerelease = version.includes("-");
  const releaseUrl = `https://github.com/${repo}/releases/tag/${tag}`;
  const notesFile = `docs/RELEASE_NOTES_${tag}.md`;
  const notesUrl = existsSync(path.join(root, notesFile))
    ? `https://github.com/${repo}/blob/${tag}/${notesFile}`
    : releaseUrl;
  const benchmarkUrl = existsSync(benchmarksDocPath)
    ? `https://github.com/${repo}/blob/${tag}/docs/BENCHMARKS.md`
    : `https://github.com/${repo}/blob/main/docs/BENCHMARKS.md`;

  const release = {
    tag,
    version,
    prerelease,
    repo,
    releaseUrl,
    notesUrl,
    benchmarkUrl,
    downloadLabel: prerelease ? "Download unsigned prerelease" : "Download for Windows",
    channel: prerelease ? "is a testing candidate." : "is available for Windows.",
    warning: prerelease
      ? "Unsigned testing candidate. Windows may warn and SmartScreen has no reputation for it. This is not a publicly trusted production release."
      : "The Windows installer is unsigned. Windows may show an unknown-publisher or SmartScreen warning.",
  };

  return `// Generated by scripts/sync-landing.mjs from the release tag.
// Do not edit by hand: run \`npm run landing:sync -- --tag ${tag}\`.
export const RELEASE = ${JSON.stringify(release, null, 2)};
`;
}

try {
  const pkg = readPackage();
  const tag = resolveTag();
  const repo = repositorySlug(pkg);
  const benchmarks = parseBenchmarks();

  const outputs = [
    { file: benchmarksPath, label: "landing/benchmarks.js", content: renderBenchmarks(benchmarks) },
    { file: releasePath, label: "landing/release.js", content: renderRelease(tag, repo) },
  ];

  const stale = [];
  for (const output of outputs) {
    let current = null;
    try {
      current = readFileSync(output.file, "utf8").replace(/\r\n/g, "\n");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (current === output.content) continue;
    stale.push(output.label);
    if (!check) writeFileSync(output.file, output.content);
  }

  if (check) {
    if (stale.length) {
      console.error("LANDING_SYNC_STALE");
      for (const file of stale) console.error(` - ${file} is out of date; run npm run landing:sync`);
      process.exit(1);
    }
    console.log(`LANDING_SYNC_OK (${tag}, ${benchmarks.rows.length} benchmark rows, ${repo})`);
  } else {
    console.log(
      `LANDING_SYNC_WROTE ${stale.length ? stale.join(", ") : "no changes"} (${tag}, ${benchmarks.rows.length} benchmark rows)`,
    );
  }
} catch (error) {
  fail(error.message);
}
